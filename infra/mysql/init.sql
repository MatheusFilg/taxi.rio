CREATE TABLE IF NOT EXISTS corridas (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  passageiro_id VARCHAR(64) NOT NULL,
  origem VARCHAR(255) NOT NULL,
  destino VARCHAR(255) NOT NULL,
  status VARCHAR(32) NOT NULL,
  created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3)
);

CREATE TABLE IF NOT EXISTS corridas_idempotencia (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  idempotency_key VARCHAR(64) NOT NULL,
  passageiro_id VARCHAR(64) NOT NULL,
  corrida_id BIGINT UNSIGNED NOT NULL,
  response_json JSON NOT NULL,
  created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  UNIQUE KEY uq_idempotency_passageiro (idempotency_key, passageiro_id),
  CONSTRAINT fk_idem_corrida FOREIGN KEY (corrida_id) REFERENCES corridas (id)
);

CREATE TABLE IF NOT EXISTS processed_events (
  event_id CHAR(36) NOT NULL PRIMARY KEY,
  processed_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
);
